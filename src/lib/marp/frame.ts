import frameRuntimeSource from "./frameRuntime.js?raw";

export function allowedLink(href: string): boolean {
  if (!href || href.length > 4096 || /[\u0000-\u0020\u007f\\]/.test(href) || href.startsWith("//")) return false;
  return !/^[a-z][a-z\d+.-]*:/i.test(href) || /^(https?:|mailto:)/i.test(href);
}

export interface FrameMessage {
  channel: "maca-marp";
  session: string;
  generation: number;
  type: "ready" | "rendered" | "slide" | "link";
  index?: number;
  href?: string;
}

export function readFrameMessage(event: MessageEvent, source: Window | null, session: string, generation: number, count: number): FrameMessage | null {
  const message = event.data;
  if (!source || event.source !== source || !message || typeof message !== "object" ||
      Object.keys(message).length > 7 || message.channel !== "maca-marp" || message.session !== session) return null;
  if (message.type === "ready" && message.generation === 0) return message;
  if (message.generation !== generation) return null;
  if (message.type === "rendered") return message;
  if (message.type === "slide" && Number.isInteger(message.index) && message.index >= 0 && message.index < count) return message;
  if (message.type === "link" && typeof message.href === "string" && allowedLink(message.href)) return message;
  return null;
}

// Only this bundled helper runs inside the opaque-origin frame. It exposes no
// application commands and accepts render/slide messages only from its parent.

export function createFrameSession(): string {
  return [...crypto.getRandomValues(new Uint8Array(16))].map((value) => value.toString(16).padStart(2, "0")).join("");
}

export function createFrameShell(session: string): string {
  const nonce = createFrameSession();
  // Session is generated by us, never taken from a document.
  if (!/^[\w-]+$/.test(session)) throw new Error("Invalid frame session");
  const csp = `default-src 'none'; script-src 'nonce-${nonce}'; style-src 'unsafe-inline'; img-src data:; font-src 'none'; connect-src 'none'; media-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'`;
  return `<!doctype html><html data-session="${session}"><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="${csp}"><style id="theme"></style><style>html{color-scheme:light;background:#ddd}body{margin:0;padding:12px}article{margin:0 0 16px}article>div.marpit{margin:0}svg[data-marpit-svg]{display:block;width:100%;height:auto}article:last-child{margin-bottom:0}a{cursor:pointer}</style></head><body><main id="deck"></main><script nonce="${nonce}">${frameRuntimeSource}</script></body></html>`;
}
