export function allowedLink(href: string): boolean {
  if (!href || href.length > 4096 || /[\u0000-\u0020\u007f\\]/.test(href) || href.startsWith("//")) return false;
  return !/^[a-z][a-z\d+.-]*:/i.test(href) || /^(https?:|mailto:)/i.test(href);
}

export interface FrameMessage {
  channel: "maca-marp";
  session: string;
  generation: number;
  type: "ready" | "rendered" | "slide" | "link";
  index?: number;
  href?: string;
}

export function readFrameMessage(event: MessageEvent, source: Window | null, session: string, generation: number, count: number): FrameMessage | null {
  const message = event.data;
  if (!source || event.source !== source || !message || typeof message !== "object" ||
      Object.keys(message).length > 7 || message.channel !== "maca-marp" || message.session !== session) return null;
  if (message.type === "ready" && message.generation === 0) return message;
  if (message.generation !== generation) return null;
  if (message.type === "rendered") return message;
  if (message.type === "slide" && Number.isInteger(message.index) && message.index >= 0 && message.index < count) return message;
  if (message.type === "link" && typeof message.href === "string" && allowedLink(message.href)) return message;
  return null;
}

// Only this bundled helper runs inside the opaque-origin frame. It exposes no
// application commands and accepts render/slide messages only from its parent.
function frameRuntime(session: string) {
  let generation = 0;
  let current = -1;
  let slides: HTMLElement[] = [];
  const send = (type: string, values = {}) => parent.postMessage({ channel: "maca-marp", session, generation, type, ...values }, "*");
  const go = (index: number) => {
    if (!Number.isInteger(index) || index < 0 || index >= slides.length) return;
    current = index;
    window.scrollTo(0, slides[index].offsetTop);
    send("slide", { index });
  };
  window.addEventListener("message", (event) => {
    const message = event.data;
    if (event.source !== parent || !message || typeof message !== "object" || Object.keys(message).length > 9 ||
        message.channel !== "maca-marp" || message.session !== session || !Number.isSafeInteger(message.generation)) return;
    if (message.type === "hello") { send("ready"); return; }
    if (message.type === "render" && message.generation > generation && typeof message.html === "string" &&
        typeof message.css === "string" && message.html.length + message.css.length <= 32 * 1024 * 1024) {
      generation = message.generation;
      document.getElementById("theme")!.textContent = message.css;
      document.getElementById("deck")!.innerHTML = message.html;
      slides = [...document.querySelectorAll<HTMLElement>("article[data-slide-index]")];
      go(Math.max(0, Math.min(slides.length - 1, Number.isInteger(message.index) ? message.index : 0)));
      send("rendered");
    } else if (message.type === "go" && message.generation === generation) go(message.index);
  });
  let scheduled = false;
  window.addEventListener("scroll", () => {
    if (scheduled) return;
    scheduled = true;
    requestAnimationFrame(() => {
      scheduled = false;
      let index = 0;
      slides.forEach((slide, candidate) => { if (slide.getBoundingClientRect().top <= innerHeight * 0.35) index = candidate; });
      if (scrollY > 0 && scrollY + innerHeight >= document.documentElement.scrollHeight - 2) index = slides.length - 1;
      if (index !== current) { current = index; send("slide", { index }); }
    });
  }, { passive: true });
  document.addEventListener("click", (event) => {
    const link = (event.target as Element)?.closest?.("a");
    if (!link) return;
    event.preventDefault();
    const href = link.getAttribute("href") ?? "";
    if (href.startsWith("#")) {
      let id: string;
      try { id = decodeURIComponent(href.slice(1)); } catch { return; }
      const target = document.getElementById(id)?.closest("article[data-slide-index]");
      if (target) go(slides.indexOf(target as HTMLElement));
    } else if (href.length <= 4096) send("link", { href });
  }, true);
  document.addEventListener("keydown", (event) => {
    if (event.key === "PageDown" || event.key === "PageUp") {
      event.preventDefault();
      go(current + (event.key === "PageDown" ? 1 : -1));
    }
  });
  send("ready");
}

export function createFrameSession(): string {
  return [...crypto.getRandomValues(new Uint8Array(16))].map((value) => value.toString(16).padStart(2, "0")).join("");
}

export function createFrameShell(session: string): string {
  const nonce = createFrameSession();
  // Session is generated by us, never taken from a document.
  if (!/^[\w-]+$/.test(session)) throw new Error("Invalid frame session");
  const csp = `default-src 'none'; script-src 'nonce-${nonce}'; style-src 'unsafe-inline'; img-src data:; font-src 'none'; connect-src 'none'; media-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'`;
  return `<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="${csp}"><style id="theme"></style><style>html{color-scheme:light;background:#ddd}body{margin:0;padding:12px}article{margin:0 0 16px}article>div.marpit{margin:0}svg[data-marpit-svg]{display:block;width:100%;height:auto}article:last-child{margin-bottom:0}a{cursor:pointer}</style></head><body><main id="deck"></main><script nonce="${nonce}">(${frameRuntime.toString()})(${JSON.stringify(session)})</script></body></html>`;
}
